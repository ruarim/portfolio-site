export interface ModuleRect {
	x: number;
	y: number;
}

export interface WordmarkLayout {
	width: number;
	height: number;
	modules: ModuleRect[];
}

export function layoutWordmark(text: string): WordmarkLayout {
	const lines = text.toLowerCase().split('\n');
	const advance = GLYPH_COLS + 1;
	const lineAdvance = GLYPH_ROWS + 1;
	const lineWidths = lines.map((line) => Math.max(0, line.length * advance - 1));
	const width = Math.max(0, ...lineWidths);
	const height = Math.max(0, lines.length * lineAdvance - 1);
	const modules: ModuleRect[] = [];

	lines.forEach((line, lineIndex) => {
		const originY = lineIndex * lineAdvance;

		Array.from(line).forEach((char, charIndex) => {
			const glyph = glyphs[char] ?? glyphs[' '];
			const originX = charIndex * advance;

			glyph.forEach((row, y) => {
				Array.from(row).forEach((cell, x) => {
					if (cell === '#') {
						modules.push({ x: originX + x, y: originY + y });
					}
				});
			});
		});
	});

	return { width, height, modules };
}
